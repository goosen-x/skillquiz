import type { Metadata } from 'next'
import Link from 'next/link'
import { TextPage } from '@/components/layout/TextPage'
import { getAllQuizzes, getCategoriesWithCounts } from '@/lib/quiz/catalog'
import { testsLabel } from '@/lib/utils/pluralize'

export const metadata: Metadata = {
	title: 'О проекте',
	description:
		'SkillQuiz: бесплатные психологические и развивающие тесты с подробным разбором результата. Как устроены тесты, откуда берутся шкалы и чего от них не стоит ждать.',
	alternates: { canonical: '/about' }
}

export default function AboutPage() {
	const total = getAllQuizzes().length
	const categories = getCategoriesWithCounts()
	return (
		<TextPage title='О проекте' lead='Тесты, после которых понятно, что делать дальше.' path='/about'>
			<p>
				SkillQuiz собирает психологические и развивающие тесты в одном месте: сейчас их {testsLabel(total)}, от темперамента
				и стиля привязанности до финансовой грамотности. Каждый тест заканчивается не ярлыком «вы интроверт», а разбором:
				что значит результат, какие у вас сильные стороны, над чем можно поработать и с чего начать на этой неделе.
			</p>

			<h2>Как устроены тесты</h2>
			<p>
				Тесты бывают разные, и результат у них разный. Где-то считается уровень (стресс, тревожность), где-то тип
				(темперамент, язык любви), где-то профиль из нескольких шкал (Большая пятёрка), где-то процент верных ответов. Для
				каждого вида у нас свой шаблон результата, поэтому разбор всегда полный и без пустых мест.
			</p>
			<p>
				Многие тесты построены по мотивам известных моделей: теории привязанности Боулби, модели конфликтов
				Томаса-Килманна, Большой пятёрки. Но это авторские опросники для самопознания, а не клинические методики. В
				описании каждого теста честно написано, на чём он основан и как считается результат.
			</p>

			<h2>Чего от тестов не стоит ждать</h2>
			<p>
				Ни один онлайн-тест не ставит диагноз. Если результат говорит о высоком стрессе, тревоге или низкой самооценке,
				это повод присмотреться к себе и, возможно, поговорить со специалистом. Финансовые тесты не дают индивидуальных
				инвестиционных рекомендаций.
			</p>

			<h2>Сравнение с другими</h2>
			<p>
				После теста видно, как ваш результат выглядит на фоне других прошедших. Для этого мы храним только сами баллы, без
				имени, почты и других данных. Пока прохождений меньше тридцати, сравнение строится по ориентировочному
				распределению, и это прямо написано рядом с цифрами.
			</p>

			<h2>Разделы</h2>
			<ul>
				{categories.map(c => (
					<li key={c.id}>
						<Link href={`/tests/category/${c.id}`}>{c.title}</Link>: {testsLabel(c.count)}
					</li>
				))}
			</ul>

			<h2>Кто делает</h2>
			<p>
				Проект делает студия GooseLabs. Нашли ошибку в тесте или хотите предложить новый? Напишите нам, контакты на{' '}
				<Link href='/contact'>отдельной странице</Link>.
			</p>
		</TextPage>
	)
}
