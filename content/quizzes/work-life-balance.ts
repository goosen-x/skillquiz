type Scale = 'load' | 'personal' | 'health' | 'relationships' | 'boundaries'

/** Вопрос с пятью вариантами от худшего баланса (0 баллов) к лучшему (4 балла) */
function ask(
	scale: Scale,
	text: string,
	options: string[]
): PointsQuestion<Scale> {
	return {
		text,
		options: options.map((option, i) => ({
			text: option,
			points: { [scale]: i }
		}))
	}
}

