/** Расчёт ограничен двумя годами: дальше точность ответов-диапазонов теряет смысл */
const MAX_MONTHS = 24
/** Инвестиции учитываются с дисконтом: в кризис цены падают, при продаже бывает налог */
const INVEST_HAIRCUT = 0.8

type Vars = Record<
	| 'expenses'
	| 'debt'
	| 'savings'
	| 'invest'
	| 'otherIncome'
	| 'cut'
	| 'dependents'
	| 'stability',
	number
>

/** Доступный запас, тыс. ₽ */
const reserve = (v: Vars) => v.savings + v.invest * INVEST_HAIRCUT
/** Сколько придётся тратить в месяц без основного дохода, тыс. ₽ */
const burn = (v: Vars) =>
	Math.max(0, v.expenses * (1 - v.cut) + v.debt - v.otherIncome)
/** Ориентир запаса в месяцах: база по типу дохода плюс месяц на каждого иждивенца, но не больше двух */
const target = (v: Vars) => v.stability + Math.min(v.dependents, 2)

