import { defineIndexQuiz } from '@/lib/quiz/define'
import type { PointsQuestion } from '@/lib/quiz/types'

type Scale = 'contact' | 'persuasion' | 'resilience' | 'drive' | 'relations'

/** Каждый вариант даёт баллы одной шкале, к которой относится вопрос */
function ask(
	scale: Scale,
	text: string,
	options: string[]
): PointsQuestion<Scale> {
	return {
		text,
		options: options.map((label, i) => ({
			text: label,
			points: { [scale]: i }
		}))
	}
}

