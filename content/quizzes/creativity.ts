/** Вопрос с четырьмя вариантами от привычного подхода (0 баллов) к самому нестандартному (3 балла) */
function ask(
	scale: Scale,
	text: string,
	options: string[]
): PointsQuestion<Scale> {
	return {
		text,
		options: options.map((option, i) => ({
			text: option,
			points: { [scale]: i }
		}))
	}
}

