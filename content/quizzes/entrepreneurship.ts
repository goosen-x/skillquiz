import { defineIndexQuiz } from '@/lib/quiz/define'
import type { PointsQuestion } from '@/lib/quiz/types'

type Scale =
	| 'risk'
	| 'ideas'
	| 'leadership'
	| 'persistence'
	| 'opportunities'
	| 'resources'

/** Варианты идут от 0 до 4 баллов шкале, к которой относится вопрос */
function ask(
	scale: Scale,
	text: string,
	options: string[]
): PointsQuestion<Scale> {
	return {
		text,
		options: options.map((label, i) => ({
			text: label,
			points: { [scale]: i }
		}))
	}
}

