type Scale = 'emotions' | 'cues' | 'communication' | 'relations' | 'groups'

/** Вопрос-ситуация: каждый вариант даёт баллы одной шкале */
function situation(
	scale: Scale,
	text: string,
	options: Array<[string, number]>
): PointsQuestion<Scale> {
	return {
		text,
		options: options.map(([label, points]) => ({
			text: label,
			points: { [scale]: points }
		}))
	}
}

