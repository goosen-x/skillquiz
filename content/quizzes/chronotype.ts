type Chronotype = 'lark' | 'dove' | 'owl'

/**
 * Вариант ответа со сдвигом от −3 (сова) до +3 (жаворонок), как в старом
 * подсчёте баллами. Сильный сдвиг отдаёт два голоса крайнему типу, слабый
 * делит голоса между ним и голубем, середина целиком уходит голубю.
 */
function at(text: string, shift: number): PointsOption<Chronotype> {
	if (shift >= 2) return { text, points: { lark: 2 } }
	if (shift === 1) return { text, points: { lark: 1, dove: 1 } }
	if (shift === 0) return { text, points: { dove: 2 } }
	if (shift === -1) return { text, points: { owl: 1, dove: 1 } }
	return { text, points: { owl: 2 } }
}

